var (
	builtinCNOnce sync.Once
	builtinCN     []netip.Prefix
)

// builtinCNPrefixes 返回内置 CN 兜底前缀表（进程内单例）。
func builtinCNPrefixes() []netip.Prefix {
	builtinCNOnce.Do(func() {
		out := make([]netip.Prefix, 0, len(builtinCNCIDR))
		for _, c := range builtinCNCIDR {
			if p, err := netip.ParsePrefix(c); err == nil {
				out = append(out, p.Masked())
			}
		}
		builtinCN = out
	})
	return builtinCN
}

// builtinCNContains 判断 ip 是否落在内置 CN 兜底表内。
func builtinCNContains(ip netip.Addr) bool {
	if !ip.IsValid() || ip.Is4() == false {
		// 内置表仅覆盖 IPv4；v6 交给真实库（v6 段表太大，不内置）。
		return false
	}
	for _, p := range builtinCNPrefixes() {
		if p.Contains(ip) {
			return true
		}
	}
	return false
}
